"""Bundle the interactive layer: src/core.* + src/features/* -> assets/app.js, assets/app.css.
Run from the repo root: python3 tools/build.py
It also stamps index.html with a content hash so browsers fetch the new bundle.
Files are read with universal newlines and always written with LF, and paths in the bundle headers use
forward slashes, so the output is byte-identical on Windows (including CRLF checkouts), macOS and Linux."""
import hashlib, json, os, re, glob, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def fail(msg):
    sys.exit('build.py: ' + msg)
# Old hash links such as /#check now have pages. src/pages/pages.json gives each page its old key ("hashKey"); that one table
# feeds the report bundle (CV.pageRoutes) and the redirect in the <head> of index.html. Paths are relative to the report at /.
_pages = json.loads(open(os.path.join(ROOT, 'src', 'pages', 'pages.json'), encoding='utf-8').read())
ROUTES = {e['hashKey']: e['slug'] + '/' for e in _pages if isinstance(e, dict) and e.get('hashKey') and e.get('slug')}
ROUTES_JSON = json.dumps(ROUTES, sort_keys=True, separators=(',', ':'))
# Optional email capture. The endpoint has to be a path on this site, so the page's Content-Security-Policy (connect-src 'self') never
# needs widening. Anything else is refused here.
_cfg = json.loads(open(os.path.join(ROOT, 'src', 'pages', 'config.json'), encoding='utf-8').read())
_same_origin_path = re.compile(r'^/[a-z0-9][a-z0-9/_-]*/?$')
CONFIG = {'captureEndpoint': _cfg.get('captureEndpoint', ''), 'privacyUrl': _cfg.get('privacyUrl', ''), 'wording': _cfg.get('wording', {})}
for _k in ('captureEndpoint', 'privacyUrl'):
    if CONFIG[_k] and not (isinstance(CONFIG[_k], str) and _same_origin_path.match(CONFIG[_k])): fail(f'src/pages/config.json: {_k} must be empty or a path on this site such as /api')
if CONFIG['captureEndpoint']:
    if not CONFIG['privacyUrl']: fail('src/pages/config.json: captureEndpoint needs a privacyUrl (the notice must be linked beside the form)')
    for _w in ('newsletter', 'updates'):
        _e = CONFIG['wording'].get(_w) if isinstance(CONFIG['wording'], dict) else None
        if not (isinstance(_e, dict) and re.match(r'^[a-z0-9.\-]{2,40}$', str(_e.get('id', ''))) and isinstance(_e.get('text'), str) and len(_e['text'].strip()) > 20): fail(f'src/pages/config.json: wording.{_w} needs an id (lower case letters, digits, dots and hyphens) and the text shown beside the box')
CONFIG_PART = '/* --- src/pages/config.json (generated by tools/build.py) --- */\nCV.config = ' + json.dumps(CONFIG, sort_keys=True, separators=(',', ':')) + ';\n'
def cat(ext):
    files = [os.path.join(ROOT, 'src', 'core.' + ext)] + sorted(glob.glob(os.path.join(ROOT, 'src', 'features', '*.' + ext)))
    parts = []
    for f in files:
        if os.path.exists(f):
            rel = os.path.relpath(f, ROOT).replace(os.sep, '/')
            parts.append(f'/* --- {rel} --- */\n' + open(f, encoding='utf-8').read().strip() + '\n')
            if ext == 'js' and rel == 'src/core.js':
                parts.append('/* --- src/pages/pages.json (generated by tools/build.py) --- */\nCV.pageRoutes = ' + ROUTES_JSON + ';\n')
                parts.append(CONFIG_PART)
    return '\n'.join(parts)
js, css = cat('js'), cat('css')
os.makedirs(os.path.join(ROOT, 'assets'), exist_ok=True)
open(os.path.join(ROOT, 'assets', 'app.js'), 'w', encoding='utf-8', newline='\n').write('/* Built by tools/build.py. Edit src/, not this file. */\n' + js)
open(os.path.join(ROOT, 'assets', 'app.css'), 'w', encoding='utf-8', newline='\n').write('/* Built by tools/build.py. Edit src/, not this file. */\n' + css)
v = hashlib.sha1((js + css).encode()).hexdigest()[:10]
p = os.path.join(ROOT, 'index.html'); s = open(p, encoding='utf-8').read()
s2 = re.sub(r'assets/app\.(js|css)(\?v=[0-9a-f]+)?"', lambda m: f'assets/app.{m.group(1)}?v={v}"', s)
# The redirect runs in <head>, before first paint: a link such as /#check goes straight to /check/ and the report never shows.
REDIRECT = '<script>(function(){var m=' + ROUTES_JSON + ',k=location.hash.slice(1);if(Object.prototype.hasOwnProperty.call(m,k))location.replace(m[k])})()</script>'
if '<!-- build:redirects -->' not in s2: fail('index.html has no <!-- build:redirects --> block in <head>')
s2 = re.sub(r'(<!-- build:redirects -->\n).*?(\n<!-- /build:redirects -->)', lambda m_: m_.group(1) + REDIRECT + m_.group(2), s2, flags=re.S)
if s2 != s: open(p, 'w', encoding='utf-8', newline='\n').write(s2)
print('built', v, len(js), 'js bytes', len(css), 'css bytes')

# ---- Standalone tool pages (src/pages/pages.json) -------------------------------------------------------------
# Each entry becomes <slug>/index.html plus assets/tool-<slug>.js and assets/tool-<slug>.css. The tool bundles are
# src/core.* plus only the listed features, so assets/app.js and assets/app.css above are never affected.
import sys

def rd(path):
    return open(path, encoding='utf-8').read()

def wr(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8', newline='\n').write(text)

PAGES_DIR = os.path.join(ROOT, 'src', 'pages')
SITE_URL = 'https://cyberoutlook.sbcsg.uk/'
SLUG_RE = re.compile(r'^[a-z0-9]+(-[a-z0-9]+)*$')
OPEN_RE = re.compile(r'^([A-Za-z_$][\w$]*(\.[A-Za-z_$][\w$]*)*)?$')
# Slugs that would collide with real site folders. "tools" is allowed on purpose (UX-07 uses /tools/ for the hub).
RESERVED = {'assets', 'src', 'docs', 'linkedin', 'index'}
MARK = '<!-- Built by tools/build.py from src/pages/shell.html. Edit src/pages/, not this file. -->'
HEADER = '/* Built by tools/build.py. Edit src/, not this file. */\n'

def esc(v):
    return v.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('"', '&quot;')

def feature_files(fid):
    return sorted(glob.glob(os.path.join(ROOT, 'src', 'features', fid + '-*.js'))), sorted(glob.glob(os.path.join(ROOT, 'src', 'features', fid + '-*.css')))

def part(path, body=None):
    rel = os.path.relpath(path, ROOT).replace(os.sep, '/')
    return f'/* --- {rel} --- */\n' + (rd(path) if body is None else body).strip() + '\n'

def page_bundles(ids):
    js, css = [], []
    css.append(part(os.path.join(PAGES_DIR, 'shell.css')))
    js.append(part(os.path.join(ROOT, 'src', 'core.js')))
    css.append(part(os.path.join(ROOT, 'src', 'core.css')))
    # core.js assigns window.CV outright, so the flag goes straight after it, not in the page.
    js.append('/* --- standalone page flag (tools/build.py) --- */\nCV.standalone = true;\n')
    js.append(CONFIG_PART)
    js.append(part(os.path.join(PAGES_DIR, 'standalone.js')))
    for fid in ids:
        fjs, fcss = feature_files(fid)
        for f in fjs: js.append(part(f))
        for f in fcss: css.append(part(f))
    return '\n'.join(js), '\n'.join(css)

manifest = json.loads(rd(os.path.join(PAGES_DIR, 'pages.json')))
if not isinstance(manifest, list): fail('src/pages/pages.json must be a list')
shell = rd(os.path.join(PAGES_DIR, 'shell.html'))
m = re.search(r'<meta http-equiv="Content-Security-Policy" content="([^"]+)"', s)
if not m: fail('could not find the Content-Security-Policy meta tag in index.html')
CSP = m.group(1)   # taken from index.html, so every tool page carries the report page policy
# The report embeds its fonts (#31); the tool pages still load them from Google Fonts, so they also allow those two hosts.
CSP = CSP.replace("style-src 'self' 'unsafe-inline';", "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com;", 1).replace('font-src data:;', 'font-src data: https://fonts.gstatic.com;', 1)
if 'fonts.googleapis.com' not in CSP or 'fonts.gstatic.com' not in CSP: fail('could not widen the tool page policy for Google Fonts; the report policy changed shape')
mc = re.search(r"const CACHE = '([^']+)'", rd(os.path.join(ROOT, 'sw.js')))
if not mc: fail('could not find the CACHE name in sw.js')
CACHE_NAME = mc.group(1)   # tool pages write into the service worker's cache, so the name comes from sw.js

# Parts of the report that a tool reads from the page (CV.actions() reads the action tables, the IT provider email reads
# the four questions). They are lifted from index.html and put in a hidden block, so a tool page never carries its own
# copy of the wording. A page lists the parts it needs in "reportParts" in pages.json.
REPORT_PART_HTML = {}
# The three action tables. Ids are positional (t1-1, t3-6), so the order and count matter: fail unless there are exactly three.
tables = re.findall(r'<table class="actions">.*?</table>', s, re.S)
if len(tables) != 3: fail(f'expected exactly three <table class="actions"> blocks in index.html, found {len(tables)}')
REPORT_PART_HTML['actions'] = '\n'.join(tables)
# The "What to do" heading and its numbered list of questions for an IT provider (the email builder finds the list from the heading).
m_q = re.search(r'<h3 id="h-what-to-do">.*?</h3>.*?(<ol>.*?</ol>)', s, re.S)
if not m_q: fail('could not find the "What to do" heading and its list in index.html')
if m_q.group(1).count('<li>') != 4: fail(f'expected four questions in the "What to do" list, found {m_q.group(1).count("<li>")}')
REPORT_PART_HTML['it-questions'] = '<div class="prose">\n<h3 id="h-what-to-do">' + re.search(r'<h3 id="h-what-to-do">(.*?)</h3>', s, re.S).group(1) + '</h3>\n' + m_q.group(1) + '\n</div>'

def entry_html(en, where):
    """The optional "entry" block on a tool page: what the visitor gets, and one survey figure. Plain text in, escaped markup out."""
    if not isinstance(en, dict): fail(f'{where}: "entry" must be an object')
    gets, stat = en.get('gets', []), en.get('stat')
    if not isinstance(gets, list) or not (1 <= len(gets) <= 4) or not all(isinstance(g, str) and g.strip() for g in gets): fail(f'{where}: entry "gets" must be one to four non-empty strings')
    html = '<div class="entry-scale" aria-hidden="true">' + '<i></i>' * 10 + '</div>' + chr(10)
    html += '<ul class="entry-gets" aria-label="What you get">' + ''.join(f'<li><span class="eg-n" aria-hidden="true">{i:02d}</span><span>{esc(g)}</span></li>' for i, g in enumerate(gets, 1)) + '</ul>\n'
    if stat is not None:
        if not isinstance(stat, dict) or not all(isinstance(stat.get(k), str) and stat[k].strip() for k in ('figure', 'text', 'source')): fail(f'{where}: entry "stat" needs non-empty "figure", "text" and "source"')
        html += f'<p class="entry-stat"><b>{esc(stat["figure"])}</b><span>{esc(stat["text"])}</span><small>{esc(stat["source"])}</small></p>\n'
    return html


def hub_html(hub, where):
    # A list of plain links (no JavaScript needed). Cards come from the "card" of each tool page, in the order given.
    if not isinstance(hub, dict) or not isinstance(hub.get('order'), list) or not isinstance(hub.get('reportTools', []), list): fail(f'{where}: "hub" needs "order" (list of slugs) and optionally "reportTools" (list)')
    by_slug = {x.get('slug'): x for x in manifest}
    items = []
    for slug in hub['order']:
        pg = by_slug.get(slug)
        if not pg or not isinstance(pg.get('card'), dict) or not all(isinstance(pg['card'].get(k), str) and pg['card'][k].strip() for k in ('promise', 'time')): fail(f'{where}: hub order "{slug}" is not a page with a card (promise and time)')
        items.append(f'<li class="hub-card"><h2><a href="../{slug}/">{esc(pg["title"])}</a></h2><p>{esc(pg["card"]["promise"])}</p><p class="hub-meta">{esc(pg["card"]["time"])}</p></li>')
    out = '<ul class="hub-list">\n' + '\n'.join(items) + '\n</ul>\n'
    routes = rd(os.path.join(ROOT, 'src', 'features', '171-tool-links.js'))
    rep = []
    for t in hub.get('reportTools', []):
        if not isinstance(t, dict) or not all(isinstance(t.get(k), str) and t[k].strip() for k in ('key', 'name', 'promise')): fail(f'{where}: each reportTools entry needs key, name and promise')
        if not re.search(r'\b' + re.escape(t['key']) + r':\s*function', routes): fail(f'{where}: reportTools key "{t["key"]}" is not a route in src/features/171-tool-links.js')
        rep.append(f'<li class="hub-card"><h3><a href="../#{t["key"]}">{esc(t["name"])}</a></h3><p>{esc(t["promise"])}</p><p class="hub-meta">Opens in the report</p></li>')
    if rep: out += '<h2 class="hub-sub">More tools, inside the report</h2>\n<ul class="hub-list">\n' + '\n'.join(rep) + '\n</ul>\n'
    return out

seen, wanted_files, listing = set(), set(), []
# Titles, descriptions and addresses must be unique across pages and the report, so no two links preview the same way.
titles, descriptions, urls = {}, {}, {SITE_URL: 'the report'}
m_t = re.search(r'<title>(.*?)</title>', s, re.S); m_d = re.search(r'<meta name="description" content="(.*?)">', s, re.S)
if m_t: titles[m_t.group(1).strip()] = 'the report'
if m_d: descriptions[m_d.group(1).strip()] = 'the report'
for i, e in enumerate(manifest):
    where = f'pages.json entry {i + 1}'
    for k in ('slug', 'title', 'description'):
        if not isinstance(e.get(k), str) or not e[k].strip(): fail(f'{where}: "{k}" must be a non-empty string')
    slug = e['slug']; where = f'pages.json entry "{slug}"'
    if not SLUG_RE.match(slug): fail(f'{where}: slug must be lower case letters, digits and single hyphens')
    if slug in RESERVED: fail(f'{where}: slug is reserved')
    if slug in seen: fail(f'{where}: duplicate slug')
    seen.add(slug)
    ids = e.get('features', [])
    if not isinstance(ids, list) or not all(isinstance(x, str) and re.match(r'^\d{3}$', x) for x in ids): fail(f'{where}: "features" must be a list of three-digit ids as strings')
    for fid in ids:
        fjs, fcss = feature_files(fid)
        if not fjs and not fcss: fail(f'{where}: feature {fid} matches no file in src/features')
    ids = sorted(set(ids), key=int)
    opn = e.get('open', '')
    if not isinstance(opn, str) or not OPEN_RE.match(opn): fail(f'{where}: "open" must be a dotted function path such as CV.openCheck')
    hk = e.get('hashKey')
    if hk is not None and (not isinstance(hk, str) or not re.search(r'\b' + re.escape(hk) + r':\s*function', rd(os.path.join(ROOT, 'src', 'features', '171-tool-links.js')))): fail(f'{where}: hashKey "{hk}" is not a route in src/features/171-tool-links.js')
    lm = e.get('lastmod')
    if not isinstance(lm, str) or not re.match(r'^\d{4}-\d{2}-\d{2}$', lm): fail(f'{where}: "lastmod" must be a date such as 2026-11-11 (kept by hand so the build is the same every day)')
    for field, bucket in (('title', titles), ('description', descriptions), ('url', urls)):
        val = e[field] if field != 'url' else f'{SITE_URL}{slug}/'
        if val in bucket: fail(f'{where}: {field} is already used by "{bucket[val]}"')
        bucket[val] = slug
    og = e.get('ogImage', 'assets/og-image.png')
    if not isinstance(og, str) or og.startswith('/') or '..' in og or not os.path.isfile(os.path.join(ROOT, *og.split('/'))): fail(f'{where}: ogImage must be an existing file path inside the repo')
    pjs, pcss = page_bundles(ids)
    v = hashlib.sha1((pjs + pcss).encode()).hexdigest()[:10]
    wr(os.path.join(ROOT, 'assets', f'tool-{slug}.js'), HEADER + pjs)
    wr(os.path.join(ROOT, 'assets', f'tool-{slug}.css'), HEADER + pcss)
    intro = e.get('intro', '')
    if not isinstance(intro, str): fail(f'{where}: "intro" must be a string')
    parts = e.get('reportParts', [])
    if not isinstance(parts, list) or not all(p_ in REPORT_PART_HTML for p_ in parts): fail(f'{where}: "reportParts" must be a list of: ' + ', '.join(sorted(REPORT_PART_HTML)))
    values = {'CSP': CSP, 'TITLE': e['title'], 'HEADING': e['title'], 'DESCRIPTION': e['description'], 'URL': f'{SITE_URL}{slug}/',
              'OG_IMAGE': SITE_URL + og, 'SLUG': slug, 'HASH': v, 'OPEN': opn, 'CACHE': CACHE_NAME}
    out = shell
    # These two are markup, filled before the escaped plain-text values. Their own text is escaped here.
    out = out.replace('{{INTRO}}', f'<p class="page-intro">{esc(intro)}</p>\n' if intro.strip() else '')
    out = out.replace('{{ENTRY}}', entry_html(e['entry'], where) if 'entry' in e else '')
    out = out.replace('{{HUB}}', hub_html(e['hub'], where) if 'hub' in e else '')
    out = out.replace('{{REPORT_PARTS}}', ('<div id="report-parts" hidden>\n' + '\n'.join(REPORT_PART_HTML[p_] for p_ in parts) + '\n</div>\n') if parts else '')
    for k, val in values.items(): out = out.replace('{{' + k + '}}', esc(val))
    if '{{' in out: fail(f'{where}: shell.html has a placeholder build.py does not fill')
    out = out.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + MARK + '\n', 1)
    wr(os.path.join(ROOT, slug, 'index.html'), out)
    wanted_files |= {f'assets/tool-{slug}.js', f'assets/tool-{slug}.css', f'{slug}/index.html'}
    listing.append(slug)
    print(f'page /{slug}/: {len(out)} html, {len(pjs) + len(HEADER)} js, {len(pcss) + len(HEADER)} css bytes, features {",".join(ids) or "none"}, v={v}')

